# ==========================================================
# OUTPUT VARIABLES
# ==========================================================
# print() is used to output variables.
x = "Python is awesome"
print(x)

# Output several variables separated by commas:
x = "Python"
y = "is"
z = "awesome"
print(x, y, z)

# The + operator also joins strings (note: no automatic spaces):
print(x + " " + y + " " + z)

# For numbers, + is a math operator:
a = 5
b = 10
print(a + b)

# Mixing a string and a number with + gives an error:
# print(5 + "Ravi")     # TypeError

# The comma works with different types:
print(a, "Ravi")
