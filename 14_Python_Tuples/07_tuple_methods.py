# ==========================================================
# TUPLE METHODS
# ==========================================================
# Tuples have two built-in methods:
thistuple = (1, 3, 7, 8, 7, 5, 4, 6, 8, 5)

# count() - how many times a value occurs
print(thistuple.count(5))      # 2

# index() - position of the first occurrence
print(thistuple.index(8))      # 3
