# ==========================================================
# PYTHON COMMENTS
# ==========================================================
# Comments can be used to:
#   - explain code
#   - make code more readable
#   - stop code from running while you test

# ---------- Creating a comment ----------
# A comment starts with #, Python ignores the rest of that line.
print("Hello, World!")

print("Hello, again!")  # a comment can also be at the end of a line

# Use # to stop a line of code from running:
# print("This will not be printed")
print("Only this is printed")

# ---------- Multi-line comments ----------
# Python has no special multi-line comment syntax.
# Option 1: put a # in front of each line
# like this
# and this

# Option 2: a string literal that is not assigned to a variable is ignored,
# so a triple-quoted string can act as a multi-line comment:
"""
This is a comment
written over
more than one line
"""
print("Comments lesson finished")
