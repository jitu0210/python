# ==========================================================
# PYTHON OUTPUT - PRINT TEXT
# ==========================================================
# The print() function displays output on the screen.

print("Hello World!")

# Text must be inside quotes - single or double, both work:
print("Double quotes")
print('Single quotes')

# Every print() starts on a new line by default:
print("First line")
print("Second line")

# Print several values: separate them with commas (a space is added between)
print("I", "am", "learning", "Python")

# Change the separator with sep=
print("2026", "11", "16", sep="-")

# Print on the same line with end=  (default end is a new line "\n")
print("Hello", end=" ")
print("World!")

# Empty print() gives an empty line
print()
print("After a blank line")
