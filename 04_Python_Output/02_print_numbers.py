# ==========================================================
# PYTHON OUTPUT - PRINT NUMBERS
# ==========================================================
# Numbers are printed WITHOUT quotes:
print(3)
print(358)
print(50000)
print(2.75)

# You can do math directly inside print():
print(3 + 3)
print(2 * 5)
print(10 / 4)

# A number inside quotes is TEXT, not a number:
print("3 + 3")     # prints the text 3 + 3
print(3 + 3)       # prints 6

# Mix text and numbers with a comma:
print("I am", 35, "years old.")
print("Total:", 4 * 25)
