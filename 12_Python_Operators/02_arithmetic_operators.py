# ==========================================================
# ARITHMETIC OPERATORS
# ==========================================================
x = 15
y = 4

print(x + y)    # Addition        19
print(x - y)    # Subtraction     11
print(x * y)    # Multiplication  60
print(x / y)    # Division        3.75
print(x % y)    # Modulus         3   (remainder)
print(x ** y)   # Exponentiation  50625
print(x // y)   # Floor division  3   (rounds down)

# Division always returns a float:
print(12 / 3)   # 4.0

# Floor division rounds DOWN, also for negatives:
print(-15 // 4) # -4
