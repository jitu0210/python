# Python is a popular programming language created by Guido van Rossum
# and first released in 1991.
#
# What can Python do?
#   - build web applications (server side)
#   - automate tasks and write scripts
#   - work with databases, read and change files
#   - handle big data and complex mathematics
#   - prototype quickly, or build production-ready software
#
# Why Python?
#   - runs on Windows, Mac, Linux, Raspberry Pi and more
#   - simple syntax, close to plain English
#   - programs are usually shorter than in many other languages
#   - runs on an interpreter, so code executes as soon as it is written
#   - supports procedural, object-oriented and functional styles
#
# Python syntax compared to other languages:
#   - a new line ends a command (no semicolons needed)
#   - INDENTATION (whitespace) defines blocks such as loops, functions
#     and classes - other languages use curly brackets { } for this

